CREATE TABLE IF NOT EXISTS route_decision_logs (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_plate                VARCHAR(255)  NOT NULL,
    origin_city                  VARCHAR(255)  NOT NULL,
    destination_city             VARCHAR(255)  NOT NULL,
    selected_corridor            VARCHAR(255)  NOT NULL,
    total_distance_km            DOUBLE PRECISION,
    estimated_duration_hours     DOUBLE PRECISION,
    risk_level                   VARCHAR(255)  NOT NULL,
    active_alerts_count          INTEGER,
    restrictions_evaluated_count INTEGER,
    agent_recommendation         VARCHAR(1500),
    created_at                   TIMESTAMP(6)  NOT NULL,
    CONSTRAINT route_decision_logs_risk_level_check CHECK (risk_level IN ('BAJO', 'MEDIO', 'ALTO', 'INTRANSITABLE'))
);

CREATE INDEX IF NOT EXISTS idx_decision_vehicle ON route_decision_logs (vehicle_plate);
CREATE INDEX IF NOT EXISTS idx_decision_corridor ON route_decision_logs (selected_corridor);
